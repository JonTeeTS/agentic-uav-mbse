function criteria = stage04_require_approval()
%STAGE04_REQUIRE_APPROVAL Prevent an unapproved pass/fail assessment.
folder = fileparts(mfilename('fullpath'));
criteria = jsondecode(fileread(fullfile(folder, 'path_followed_criteria.json')));
if ~criteria.Approved
    error('QuadMVP:CriteriaNotApproved', ...
        'PF-CRITERIA-v1 is awaiting user approval. No pass/fail assessment is authorized.');
end
if ~strcmp(criteria.Version,'PF-CRITERIA-v1') ...
        || criteria.ToleranceMeters ~= 0.20 ...
        || criteria.WaypointArrivalToleranceMeters ~= 0.20 ...
        || criteria.MaximumSimulationTimeSeconds ~= 90 ...
        || ~isequal(criteria.AssessedFlightModes(:)',[2 3 4]) ...
        || ~isequal(criteria.PathVerticesNED,[0 0 -2;2 0 -2;2 2 -2;0 2 -2])
    error('QuadMVP:ApprovedCriteriaChanged', ...
        'The criteria differ from approved PF-CRITERIA-v1. Obtain approval for a new version.');
end
end
